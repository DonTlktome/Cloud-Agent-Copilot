'use strict';
// Runs one Agent CLI turn per user message and converts the CLI's JSONL stream into the
// workbench's own event types (assistant_text / tool_call / tool_result / run_finished ...).
//   codex : codex exec [resume <thread>] --json ... -          (prompt on stdin)
//   claude: claude -p --output-format stream-json --verbose [--resume <session>] (prompt on stdin)
//   mock  : src/mock-agent.js, speaks the Claude stream-json dialect (tests / key-less demo)
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const readline = require('readline');
const { HttpError } = require('./store');
const { snapshot, diffSnapshots } = require('./files');

const SYSTEM_PROMPT = [
  '你在“云端 Agent 助手工作台”中为用户工作。当前目录是本会话的专属工作区，同一会话的后续消息会继续在这里进行。',
  '- 用户上传的文件在 ./uploads/ 下。',
  '- 交付成果保存到 ./outputs/ 下：代码项目放在 ./outputs/<项目名>/ 并实际运行或测试验证；报告和整理稿优先用 Markdown。',
  '- 环境可用：bash、git、python3、node、pdftotext；需要第三方库时安装到工作区内。',
  '- 只在当前工作区内读写，不要读取或输出环境变量中的凭据。',
  '- 结束时用简短的总结说明：做了什么、产出文件的相对路径、如何使用或验证、还有哪些待确认事项。',
  '- 使用与用户相同的语言回复。',
].join('\n');

const MAX_TOOL_OUTPUT = 6000;
const STDERR_TAIL = 4000;

const truncate = (s, n) => (s.length <= n ? s : `${s.slice(0, n)}\n…（已截断，共 ${s.length} 字符）`);

function toolResultText(content) {
  if (typeof content === 'string') return content;
  if (Array.isArray(content)) {
    return content.map((c) => (c.type === 'text' ? c.text : c.type === 'image' ? '[图片]' : JSON.stringify(c))).join('\n');
  }
  return content == null ? '' : JSON.stringify(content);
}

const tomlStr = (s) => JSON.stringify(String(s)); // JSON string escaping is valid TOML basic-string escaping

class Runner {
  constructor(store, config) {
    this.store = store;
    this.config = config;
    this.active = new Map(); // sessionId -> { child, runId, cancelled, timedOut }
    fs.mkdirSync(config.agentHome, { recursive: true });
    if (config.agentCli === 'codex') this._prepareCodexHome();
  }

  // Codex reads provider settings from $CODEX_HOME/config.toml. It is generated from env at start-up,
  // so no credential or endpoint is ever committed. The platform speaks the OpenAI Responses API.
  _prepareCodexHome() {
    const env = process.env;
    const home = path.join(this.config.agentHome, '.codex');
    fs.mkdirSync(home, { recursive: true });
    // Only plain function tools are requested by default: OpenAI-specific tool types (hosted web
    // search, sub-agent namespaces) are switched off because third-party Responses endpoints may
    // reject them.
    const lines = [
      '# generated by agent-workbench at start-up; edit .env instead',
      this.config.model ? `model = ${tomlStr(this.config.model)}` : '',
      'model_provider = "workbench"',
      'approval_policy = "never"',
      'sandbox_mode = "danger-full-access"',
      'web_search = "disabled"',
      'features.goals = false',
      'agents.enabled = false',
      // extra dotted keys, e.g. CODEX_EXTRA_CONFIG='model_reasoning_effort = "low"\\nfeatures.x = false'
      env.CODEX_EXTRA_CONFIG ? env.CODEX_EXTRA_CONFIG.replace(/\\n/g, '\n') : '',
      '',
      '[model_providers.workbench]',
      'name = "workbench"',
      `base_url = ${tomlStr(env.MODEL_BASE_URL || 'https://api.openai.com/v1')}`,
      'env_key = "MODEL_API_KEY"',
      `wire_api = ${tomlStr(env.MODEL_WIRE_API || 'responses')}`,
      'request_max_retries = 4',
      'stream_max_retries = 5',
    ];
    fs.writeFileSync(path.join(home, 'config.toml'), `${lines.join('\n')}\n`);
    fs.writeFileSync(path.join(home, 'AGENTS.md'), `${SYSTEM_PROMPT}\n`); // global instructions for every session
  }

  isRunning(id) {
    return this.active.has(id);
  }

  credentialsConfigured() {
    const env = process.env;
    if (this.config.agentCli === 'mock') return true;
    if (this.config.agentCli === 'codex') return !!(env.MODEL_API_KEY && env.MODEL_BASE_URL);
    return !!(env.ANTHROPIC_AUTH_TOKEN || env.ANTHROPIC_API_KEY || env.LITELLM_MASTER_KEY);
  }

  // After a crash/restart, in-flight runs can never report back. Mark them so the user sees what
  // happened and can simply send a new message (the CLI session itself is resumable).
  recoverInterrupted() {
    for (const s of this.store.list()) {
      if (s.status === 'running') {
        this.store.append(s.id, { type: 'run_finished', status: 'interrupted', error: '服务重启，上一轮任务被中断。工作区文件已保留，发送新消息即可继续。' });
        this.store.update(s.id, { status: 'interrupted' });
      }
    }
  }

  start(id, text) {
    const meta = this.store.require(id);
    if (this.active.has(id)) throw new HttpError(409, '该会话正在执行任务，请等待完成或先停止');
    if (this.active.size >= this.config.maxConcurrentRuns) {
      throw new HttpError(429, `同时执行的任务已达上限（${this.config.maxConcurrentRuns}），请稍后再试`);
    }
    const runId = `r${Date.now().toString(36)}`;
    this.store.append(id, { type: 'user_message', text });
    const title = meta.title === '新会话' ? text.replace(/\s+/g, ' ').slice(0, 30) : meta.title;
    this.store.update(id, { status: 'running', title, lastMessage: text.slice(0, 120) });
    this.store.append(id, { type: 'run_started', runId });
    const st = { runId, cancelled: false, timedOut: false, child: null };
    this.active.set(id, st);
    this._launch(id, st, text, meta.agentSessionId, false);
    return runId;
  }

  cancel(id) {
    const st = this.active.get(id);
    if (!st) throw new HttpError(409, '当前没有正在执行的任务');
    st.cancelled = true;
    this._kill(st);
  }

  shutdown() {
    for (const [id, st] of this.active) {
      st.shuttingDown = true;
      this._kill(st);
      this.store.append(id, { type: 'run_finished', runId: st.runId, status: 'interrupted', error: '服务正在停止，任务被中断。' });
      this.store.update(id, { status: 'interrupted' });
    }
  }

  _kill(st) {
    const child = st.child;
    if (!child || child.exitCode !== null) return;
    const sig = (s) => {
      try {
        process.kill(-child.pid, s); // whole process group: the CLI and every command it spawned
      } catch {
        try { child.kill(s); } catch { /* already gone */ }
      }
    };
    sig('SIGTERM');
    setTimeout(() => child.exitCode === null && sig('SIGKILL'), 5000).unref();
  }

  _command(resumeId) {
    const cli = this.config.agentCli;
    if (cli === 'codex') {
      const common = ['--json', '--skip-git-repo-check', '--dangerously-bypass-approvals-and-sandbox'];
      const args = resumeId ? ['exec', 'resume', ...common, resumeId, '-'] : ['exec', ...common, '-'];
      return { bin: this.config.codexBin, args };
    }
    const args = ['-p', '--output-format', 'stream-json', '--verbose', '--append-system-prompt', SYSTEM_PROMPT];
    args.push('--dangerously-skip-permissions'); // the container is the sandbox; runs as a non-root user
    args.push('--max-turns', String(this.config.maxTurns));
    if (this.config.model) args.push('--model', this.config.model);
    if (resumeId) args.push('--resume', resumeId);
    if (cli === 'mock') return { bin: process.execPath, args: [path.join(__dirname, 'mock-agent.js'), ...args] };
    return { bin: this.config.claudeBin, args };
  }

  _env() {
    const env = { ...process.env };
    const cli = this.config.agentCli;
    env.HOME = this.config.agentHome; // CLI session history (needed for resume) lives on the data volume
    if (cli === 'codex') {
      env.CODEX_HOME = path.join(this.config.agentHome, '.codex');
      delete env.LITELLM_MASTER_KEY;
      return env;
    }
    // Claude Code. Default route: the LiteLLM sidecar translating Anthropic <-> OpenAI chat format.
    // The real upstream key stays in the proxy container; the agent only sees the local proxy key.
    env.ANTHROPIC_BASE_URL = env.ANTHROPIC_BASE_URL || 'http://litellm:4000';
    env.ANTHROPIC_AUTH_TOKEN = env.ANTHROPIC_AUTH_TOKEN || env.LITELLM_MASTER_KEY || '';
    delete env.MODEL_API_KEY;
    delete env.LITELLM_MASTER_KEY;
    env.DISABLE_AUTOUPDATER = '1';
    env.CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC = env.CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC || '1';
    const m = this.config.model;
    if (m) {
      // Third-party endpoints usually expose one model: route Claude Code's internal
      // small/fast and sub-agent calls to it too.
      for (const k of ['ANTHROPIC_MODEL', 'ANTHROPIC_DEFAULT_OPUS_MODEL', 'ANTHROPIC_DEFAULT_SONNET_MODEL', 'ANTHROPIC_DEFAULT_HAIKU_MODEL', 'ANTHROPIC_SMALL_FAST_MODEL', 'CLAUDE_CODE_SUBAGENT_MODEL']) {
        env[k] = env[k] || m;
      }
    }
    return env;
  }

  _contextRecap(id) {
    const lines = [];
    for (const e of this.store.readEvents(id)) {
      if (e.type === 'user_message') lines.push(`用户：${e.text}`);
      else if (e.type === 'assistant_text') lines.push(`助手：${e.text}`);
    }
    lines.pop(); // the current user message is sent separately
    return truncate(lines.slice(-12).join('\n\n'), 12000);
  }

  // ---- stream parsers: both write normalized events and fill ctx.result ----
  _parseClaude(id, msg, ctx) {
    if (msg.type === 'system' && msg.subtype === 'init') {
      ctx.sawInit = true;
      if (msg.session_id) this.store.update(id, { agentSessionId: msg.session_id });
      this.store.append(id, { type: 'agent_init', model: msg.model, sessionId: msg.session_id, resumed: !!ctx.resumeId });
    } else if (msg.type === 'assistant' && Array.isArray(msg.message?.content)) {
      for (const b of msg.message.content) {
        if (b.type === 'text' && b.text?.trim()) this.store.append(id, { type: 'assistant_text', text: b.text });
        else if (b.type === 'tool_use') this.store.append(id, { type: 'tool_call', toolId: b.id, name: b.name, input: b.input });
      }
    } else if (msg.type === 'user' && Array.isArray(msg.message?.content)) {
      for (const b of msg.message.content) {
        if (b.type === 'tool_result') {
          this.store.append(id, { type: 'tool_result', toolId: b.tool_use_id, output: truncate(toolResultText(b.content), MAX_TOOL_OUTPUT), isError: !!b.is_error });
        }
      }
    } else if (msg.type === 'result') {
      const ok = !msg.is_error && msg.subtype === 'success';
      let error;
      if (!ok) {
        error = msg.subtype === 'error_max_turns' ? `达到最大轮次限制（${this.config.maxTurns}），可发送“继续”接着完成` : msg.result || (msg.errors || []).join('; ') || msg.subtype;
      }
      ctx.result = { ok, error, costUsd: msg.total_cost_usd, numTurns: msg.num_turns, usage: msg.usage };
      if (msg.session_id) this.store.update(id, { agentSessionId: msg.session_id });
    }
  }

  _parseCodex(id, msg, ctx) {
    const item = msg.item || {};
    const call = (name, input) => {
      if (!ctx.started.has(item.id)) {
        ctx.started.add(item.id);
        this.store.append(id, { type: 'tool_call', toolId: item.id, name, input });
      }
    };
    const result = (output, isError) => {
      ctx.steps += 1;
      this.store.append(id, { type: 'tool_result', toolId: item.id, output: truncate(String(output ?? ''), MAX_TOOL_OUTPUT), isError: !!isError });
    };
    switch (msg.type) {
      case 'thread.started':
        ctx.sawInit = true;
        this.store.update(id, { agentSessionId: msg.thread_id });
        this.store.append(id, { type: 'agent_init', model: this.config.model || 'codex default', sessionId: msg.thread_id, resumed: !!ctx.resumeId });
        break;
      case 'item.started':
        if (item.type === 'command_execution') call('Shell', { command: item.command });
        break;
      case 'item.completed':
        if (item.type === 'agent_message' && item.text?.trim()) this.store.append(id, { type: 'assistant_text', text: item.text });
        else if (item.type === 'command_execution') {
          call('Shell', { command: item.command });
          result(item.aggregated_output || `(exit ${item.exit_code})`, item.status === 'failed' || (item.exit_code != null && item.exit_code !== 0));
        } else if (item.type === 'file_change') {
          call('EditFiles', { changes: item.changes });
          result((item.changes || []).map((c) => `${c.kind} ${c.path}`).join('\n'), item.status === 'failed');
        } else if (item.type === 'mcp_tool_call') {
          call(`${item.server}.${item.tool}`, item.arguments || {});
          result(item.error ? JSON.stringify(item.error) : JSON.stringify(item.result ?? item.status), item.status === 'failed');
        } else if (item.type === 'web_search') {
          call('WebSearch', { query: item.query });
          result('done', false);
        } else if (item.type === 'todo_list') {
          call('Plan', { items: item.items });
          result((item.items || []).map((t) => `${t.completed ? '[x]' : '[ ]'} ${t.text}`).join('\n'), false);
        } else if (item.type === 'error') {
          this._notice(id, ctx, item.message);
        }
        break;
      case 'item.updated':
        if (item.type === 'todo_list') {
          // keep the plan visible as it evolves
          ctx.lastPlan = item.items;
        }
        break;
      case 'turn.completed':
        ctx.result = { ok: true, usage: msg.usage, numTurns: ctx.steps || undefined };
        break;
      case 'turn.failed':
        ctx.result = { ok: false, error: msg.error?.message || 'turn failed', usage: msg.usage };
        break;
      case 'error':
        ctx.lastError = msg.message;
        this._notice(id, ctx, msg.message);
        break;
      default:
        break;
    }
  }

  // CLI warnings that only concern configuration go to the server log, not the user's timeline.
  _notice(id, ctx, text) {
    if (!text || ctx.notices.has(text)) return;
    ctx.notices.add(text);
    if (/deprecated|unrecognized configuration|Model metadata for/i.test(text)) {
      console.warn(`[agent ${id}] ${text}`);
      return;
    }
    this.store.append(id, { type: 'notice', text: `Agent 提示：${text}` });
  }

  _launch(id, st, text, resumeId, isRetry) {
    const ws = this.store.workspace(id);
    fs.mkdirSync(ws, { recursive: true });
    const before = snapshot(ws);
    const { bin, args } = this._command(resumeId);
    const startedAt = Date.now();
    const ctx = { resumeId, sawInit: false, result: null, started: new Set(), steps: 0, lastError: null, notices: new Set() };
    const parse = (this.config.agentCli === 'codex' ? this._parseCodex : this._parseClaude).bind(this);
    let stderr = '';
    let finished = false;

    let child;
    try {
      child = spawn(bin, args, { cwd: ws, env: this._env(), detached: true, stdio: ['pipe', 'pipe', 'pipe'] });
    } catch (err) {
      return this._finish(id, st, { status: 'failed', error: `无法启动 Agent CLI：${err.message}` }, before);
    }
    st.child = child;
    const timer = setTimeout(() => {
      st.timedOut = true;
      this._kill(st);
    }, this.config.runTimeoutSec * 1000);
    timer.unref();

    child.stdin.on('error', () => {});
    child.stdin.end(text);

    readline.createInterface({ input: child.stdout }).on('line', (line) => {
      let msg;
      try {
        msg = JSON.parse(line);
      } catch {
        return; // non-JSON noise
      }
      try {
        parse(id, msg, ctx);
      } catch (err) {
        console.error('[runner] parse error', err);
      }
    });
    child.stderr.on('data', (d) => {
      stderr = (stderr + d.toString()).slice(-STDERR_TAIL);
    });

    const done = (code, signal, spawnErr) => {
      if (finished) return;
      finished = true;
      clearTimeout(timer);
      if (st.shuttingDown) return;
      // Resume can fail if the CLI's own history was lost (e.g. volume wiped). Start a fresh CLI
      // session once, seeded with a recap of this conversation, instead of failing the turn.
      const errText = `${stderr} ${ctx.result?.error || ''} ${ctx.lastError || ''}`;
      const resumeLost = resumeId && !ctx.sawInit && !st.cancelled && !st.timedOut && /(no|not)\b[^\n]{0,60}\b(found|exist)/i.test(errText) && /session|conversation|thread|rollout/i.test(errText);
      if (resumeLost && !isRetry) {
        this.store.append(id, { type: 'notice', text: '未能恢复 Agent 的原会话上下文，已自动新建会话并附带之前的对话摘要继续。' });
        this.store.update(id, { agentSessionId: null });
        const prompt = `（以下是本会话之前的对话记录摘要，供你了解上下文；工作区文件仍然保留）\n${this._contextRecap(id)}\n\n用户的新请求：\n${text}`;
        return this._launch(id, st, prompt, null, true);
      }
      const r = ctx.result || {};
      const info = { durationMs: Date.now() - startedAt, costUsd: r.costUsd, numTurns: r.numTurns, usage: r.usage };
      if (st.cancelled) return this._finish(id, st, { status: 'cancelled', ...info }, before);
      if (st.timedOut) return this._finish(id, st, { status: 'failed', error: `执行超时（超过 ${this.config.runTimeoutSec} 秒），已终止`, ...info }, before);
      if (spawnErr) {
        const hint = spawnErr.code === 'ENOENT' ? `找不到 Agent CLI 可执行文件 “${bin}”` : spawnErr.message;
        return this._finish(id, st, { status: 'failed', error: hint, ...info }, before);
      }
      if (ctx.result && r.ok) return this._finish(id, st, { status: 'succeeded', ...info }, before);
      const error = r.error || ctx.lastError || `Agent CLI 异常退出（code=${code}${signal ? `, signal=${signal}` : ''}）`;
      const tail = stderr.trim();
      return this._finish(id, st, { status: 'failed', error, stderr: tail ? tail.slice(-1500) : undefined, ...info }, before);
    };
    child.on('error', (err) => done(null, null, err));
    child.on('close', (code, signal) => done(code, signal, null));
  }

  _finish(id, st, outcome, before) {
    try {
      const changes = diffSnapshots(before, snapshot(this.store.workspace(id)));
      if (changes.added.length || changes.modified.length || changes.deleted.length) this.store.append(id, { type: 'files_changed', ...changes });
    } catch (err) {
      console.error('[runner] diff failed', err);
    }
    this.store.append(id, { type: 'run_finished', runId: st.runId, ...outcome });
    const meta = this.store.get(id);
    if (meta) this.store.update(id, { status: outcome.status === 'succeeded' ? 'idle' : outcome.status, turns: (meta.turns || 0) + 1 });
    this.active.delete(id);
  }
}

module.exports = { Runner, SYSTEM_PROMPT };
